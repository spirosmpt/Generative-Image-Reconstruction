% Πίνακας για 100 εικόνες

X2D_100im = zeros(280,280);

for j = 0:9

  for i = 0:9

       % Δημιουργία αρχικής τυχαίας εισόδου με κανονική κατανομή

       Z0 = randn(10,1);

       % Υπολογισμός της εξόδου του πρώτου επιπέδου (ReLU)

       W1 = A_1 * Z0 + B_1;

       Z1 = max(W1,0);

       % Υπολογισμός της εξόδου του δεύτερου επιπέδου (Sigmoid)

       W2 = A_2 * Z1 + B_2;

       X = 1 ./ (1 + exp(W2));

       % Μετατροπή του αποτελέσματος σε εικόνα 28x28

       X2D = reshape(X,28,28);

       % Υπολογισμός των συντεταγμένων

       row_start = j * 28 + 1; % Αρχική γραμμή

       row_end = row_start + 27; % Τελική γραμμή

       col_start = i * 28 + 1; % Αρχική στήλη

       col_end = col_start + 27; % Τελική στήλη

       % Εισαγωγή της εικόνας

       X2D_100image(row_start:row_end, col_start:col_end) = X2D;

  end

end

imshow(X2D_100image);
